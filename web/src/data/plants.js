/**
 * Native plants of the Upper Midwest, scored for two species in trouble:
 * the rusty patched bumble bee (Bombus affinis) and the monarch butterfly
 * (Danaus plexippus).
 *
 * WHY THESE TWO DRIVE THE LIST
 *
 * Monarch caterpillars can eat exactly one thing: milkweed (Asclepias).
 * A garden with nectar but no milkweed feeds passing adults and raises no
 * caterpillars, so the matcher treats milkweed as non-negotiable.
 *
 * Rusty patched bumble bee colonies run a long season. Queens come out of
 * hibernation in early spring, when almost nothing is blooming, and workers
 * are still flying in fall, later than most other bumble bees. A garden that
 * peaks in July and quits is a hungry gap at both ends, so every plant here
 * is tagged early / mid / late and the matcher spreads its picks across all
 * three.
 *
 * Grasses and sedges are in this list on purpose. They feed nobody, but
 * bumble bees nest in abandoned mouse burrows and under clumps of bunch
 * grass, and new queens spend the winter just under the soil surface. A
 * planting of nothing but flowers is a cafeteria with no housing.
 *
 * FIELDS
 *   type       'flower' | 'grass' | 'shrub'
 *   sun        'sun' 6+ hours | 'part' 3-6 hours | 'shade' under 3 hours
 *   moisture   'wet' stays damp | 'medium' normal | 'dry' sandy or drains fast
 *   soil       'sand' | 'loam' (dark and rich) | 'clay' (heavy and sticky)
 *   height     [min, max] in feet, at full size
 *   season     'early' spring | 'mid' summer | 'late' late summer and fall
 *   monarch    'host' caterpillars eat it | 'nectar' adults drink at it | null
 *   rustyPatched   true when it is a documented rusty patched bumble bee favorite
 *   standingWater  survives water actually sitting on it for days, not just damp soil
 *   spreads        runs, suckers, or self-seeds around rather than staying in a clump
 *   needsAcidSoil  genuinely wants acid ground and struggles in limey soil
 *   deerResistant  deer usually leave it alone (nothing is deer proof)
 *   saltTolerant   handles road and sidewalk salt spray
 *   easy       forgiving to grow, and easy to actually buy
 *
 * SOURCES AND HONESTY
 *
 * This list was assembled from widely published native-plant and pollinator
 * guidance for the Upper Midwest. Ranges for sun, soil, and bloom time are
 * typical values, and real plants vary by site and by year. Deer resistance
 * especially is a tendency, not a promise: a hungry deer in March will eat
 * nearly anything. Before planting, check this against a source that is
 * accountable for being right:
 *
 *   - Xerces Society pollinator plant lists    xerces.org
 *   - USFWS rusty patched bumble bee pages     fws.gov
 *   - Your state's university extension office, or a native plant nursery
 *
 * `wildflowerId` is the plant's page in the Lady Bird Johnson Wildflower
 * Center database (wildflower.org/plants/result.php?id_plant=...), linked from
 * the data page so anyone can look a row up. A few are filed there under a
 * newer scientific name than ours, such as Oligoneuron for our Solidago rigida.
 *
 * Correcting a row here is a one-line edit, which is the point of keeping the
 * data separate from the matching logic.
 *
 * WHAT IS EXTERNALLY BACKED, AND WHAT IS NOT
 *
 * `xercesListed: true` means the species appears on the Xerces Society's
 * Great Lakes pollinator plant list, checked against the copy hosted in the
 * Lady Bird Johnson Wildflower Center's plant database:
 *
 *   https://www.wildflower.org/collections/collection.php?collection=xerces_greatlakes
 *
 * All 24 species on that list are in here. That flag vouches for the species
 * being a recognised pollinator plant for this region, and for nothing else:
 * the sun, soil, height, bloom, deer, and salt values on every row, and the
 * selection of every row without the flag, are still our own and still want
 * checking. The absence of the flag is not a mark against a plant; that list
 * is short on purpose.
 */

